_NUMBER_UNIT_RE = re.compile(
    r"(?:\$\s*)?(?P<value>\d[\d,.]*\d|\d)\s*(?P<unit>%|percent|процент\w*|млн\.?|million|млрд\.?|billion|"
    r"тыс\.?|thousand|k\b)",
    re.IGNORECASE,
)


def _compile(phrases: tuple[str, ...]) -> re.Pattern[str]:
    alternation = "|".join(re.escape(phrase) for phrase in sorted(phrases, key=len, reverse=True))
    return re.compile(rf"\b(?:{alternation})\b")


_BREAKING_COMPANY_PATTERN = _compile(_BREAKING_COMPANY_PHRASES)
_BREAKING_SIGNAL_PATTERN = _compile(_BREAKING_SIGNAL_PHRASES)


def _normalize(text: str) -> str:
    return " ".join(unicodedata.normalize("NFKC", text).lower().replace("ё", "е").split())


@dataclass(frozen=True)
class DataCandidate:
    value: str
    unit: str
    label: str
    evidence_fact: str


