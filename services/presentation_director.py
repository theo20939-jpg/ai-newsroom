"""NINJA PULSE Visual System v1 - AI Presentation Director + deterministic guards.

Zero new LLM call. The "AI proposal" this module consumes is the EXISTING Copywriting v8-family
output's own `viral_potential`/`meme_potential`/`story_led`/`quote` fields - already generated by
the same paid call every router-mode draft already makes, just never read for presentation intent
before now. This module never calls the LLM Gateway itself.

Strict separation of concerns (spec's own "AI is not a safety gate" rule):
    AI PROPOSES (existing Copywriting fields)
        -> DETERMINISTIC GUARD VALIDATES (this module's own pure functions)
        -> caller (worker/content_cycle.py) hands the decision to the renderer

This module does not decide whether to publish, how important a story is, which facts are true,
which source is trusted, or which media candidate to use - all of that is already decided upstream
(selection, Scoring, Editorial Relevance, Editorial Treatment, media ranking) and is passed in
here, read-only, never re-derived.

BREAKING/DATA/QUOTE all fail closed to NEWS on any grounding failure - see each guard's own
docstring. NEWS is therefore the only type this module can never "fail" to produce.
"""
